export async function createDraft(actor: Actor, raw: unknown) {
  await assertMdaCanSubmit(actor);
  const parsed = requestDraftSchema.safeParse(raw);
  if (!parsed.success) throw new ValidationError("Please correct the highlighted fields.", fieldErrors(parsed.error));
  const service = await prisma.serviceDefinition.findFirst({ where: { id: parsed.data.serviceId, active: true, category: { active: true } } });
  if (!service) throw new ValidationError("The selected service is not available.");
  return prisma.$transaction(async (tx) => {
    const req = await tx.serviceRequest.create({
      data: { ...parsed.data, mdaId: actor.mdaId!, createdById: actor.id, status: "DRAFT" },
    });
    await tx.requestStatusHistory.create({ data: { requestId: req.id, toStatus: "DRAFT", action: "create_draft", actorId: actor.id } });
    await audit(tx, { actorId: actor.id, actorEmail: actor.email, action: "request.draft_created", entityType: "ServiceRequest", entityId: req.id, after: { title: req.title } });
    return req;
  });
}

export async function updateDraft(actor: Actor, id: string, raw: unknown, expectedVersion: number) {
  await assertMdaCanSubmit(actor);
  const parsed = requestDraftSchema.safeParse(raw);
  if (!parsed.success) throw new ValidationError("Please correct the highlighted fields.", fieldErrors(parsed.error));
  const existing = await prisma.serviceRequest.findUnique({ where: { id } });
  if (!existing || existing.createdById !== actor.id || existing.mdaId !== actor.mdaId) throw new NotFoundError();
  if (existing.status !== "DRAFT") throw new AppError("Only drafts can be edited.");
  // mdaId/createdById/status are never taken from input.
  const res = await prisma.serviceRequest.updateMany({
    where: { id, version: expectedVersion, status: "DRAFT", createdById: actor.id },
    data: { ...parsed.data, version: { increment: 1 } },
  });
  if (res.count !== 1) throw new ConflictError();
  return prisma.serviceRequest.findUniqueOrThrow({ where: { id } });
}

export async function deleteDraft(actor: Actor, id: string) {
  const existing = await prisma.serviceRequest.findUnique({ where: { id } });
  if (!existing || existing.createdById !== actor.id) throw new NotFoundError();
  if (existing.status !== "DRAFT") throw new AppError("Only drafts can be deleted.");
  await prisma.serviceRequest.delete({ where: { id } });
}

/**
 * Submit a draft. Idempotent per `submissionKey` (generated by the wizard when
 * it loads), so repeated clicks or network retries cannot create duplicates.
 */
export async function submitRequest(actor: Actor, id: string, submissionKey: string) {
  await assertMdaCanSubmit(actor);
  if (!/^[A-Za-z0-9_-]{16,64}$/.test(submissionKey)) throw new ValidationError("Invalid submission key.");
  const prior = await prisma.serviceRequest.findUnique({ where: { submissionKey } });
  if (prior) {
    if (prior.createdById !== actor.id) throw new ForbiddenError();
    return prior; // duplicate click: return the already-submitted request
  }
  const req = await prisma.serviceRequest.findUnique({ where: { id }, include: { service: true, _count: { select: { attachments: true } } } });
  if (!req || req.createdById !== actor.id || req.mdaId !== actor.mdaId) throw new NotFoundError();
  const check = checkRequestTransition("submit", req.status, actor.permissions);
  if (!check.ok) throw new AppError(check.error);
  const full = requestSubmitSchema.safeParse({
    ...req,
    estimatedUsers: req.estimatedUsers ?? undefined,
    preferredCompletionDate: req.preferredCompletionDate ?? undefined,
  });
  if (!full.success) throw new ValidationError("The request is incomplete.", fieldErrors(full.error));
  if (req.service.requiredAttachments.length > req._count.attachments) {
    throw new ValidationError(`This service requires supporting documents: ${req.service.requiredAttachments.join(", ")}.`);
  }
  const suggestion = suggestPriority(req.service.defaultPriority, req.service.priorityRules, {
    urgency: req.urgency, estimatedUsers: req.estimatedUsers, legalConsiderations: req.legalConsiderations,
  });

  const submitted = await prisma.$transaction(async (tx) => {
    const reference = await nextReference(tx, "REQ");
    const now = new Date();
    const res = await tx.serviceRequest.updateMany({
      where: { id, status: "DRAFT", createdById: actor.id },
      data: {
        status: "SUBMITTED", reference, submittedAt: now, submissionKey, priority: suggestion.priority,
        assignedDepartmentId: req.service.suggestedDepartmentId, version: { increment: 1 },
      },
    });
    if (res.count !== 1) throw new ConflictError("This request was already submitted.");
    await tx.requestStatusHistory.create({ data: { requestId: id, fromStatus: "DRAFT", toStatus: "SUBMITTED", action: "submit", actorId: actor.id } });
    await audit(tx, {
      actorId: actor.id, actorEmail: actor.email, action: "request.submitted", entityType: "ServiceRequest", entityId: id,
      before: { status: "DRAFT" }, after: { status: "SUBMITTED", reference, suggestedPriority: suggestion.priority },
    });
    const triagers = await usersWithPermission(tx, "request.triage");
    await notify(tx, {
      userIds: triagers, type: "request.submitted", title: `New request ${reference}`,
      body: `${actor.mdaName ?? "An MDA"} submitted "${req.title}" (${req.service.name}).`, link: `/requests/${id}`,
    });
    await notify(tx, {
      userIds: [actor.id], type: "request.submission_confirmation", title: `Request ${reference} received`,
      body: `Your request "${req.title}" was submitted successfully and is awaiting KATDICT triage. Reference: ${reference}.`, link: `/requests/${id}`,
    });
    return tx.serviceRequest.findUniqueOrThrow({ where: { id } });
  });
  return submitted;
}

