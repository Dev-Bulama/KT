export interface TransitionPayload {
  reason?: string;
  triage?: unknown;
}

const NOTIFY_MDA_ON: Partial<Record<RequestStatus, { type: "request.information_requested" | "request.rejected" | "request.status_changed"; title: string }>> = {
  NEEDS_INFORMATION: { type: "request.information_requested", title: "Additional information requested" },
  REJECTED: { type: "request.rejected", title: "Request not approved" },
  DEFERRED: { type: "request.status_changed", title: "Request deferred" },
  UNDER_ASSESSMENT: { type: "request.status_changed", title: "Request under assessment" },
  INITIAL_TRIAGE: { type: "request.status_changed", title: "Request in triage" },
};

export async function transitionRequest(actor: Actor, id: string, action: RequestAction | string, payload: TransitionPayload, expectedVersion: number) {
  if (action === "submit" || action === "approval_decision" || action === "initiate_project") {
    throw new AppError("Use the dedicated operation for this action.");
  }
  const req = await prisma.serviceRequest.findFirst({ where: { AND: [{ id }, requestScope(actor)] }, include: { mda: true } });
  if (!req) throw new NotFoundError();
  const check = checkRequestTransition(action, req.status, actor.permissions, payload.reason);
  if (!check.ok) throw check.code === "FORBIDDEN" ? new ForbiddenError(check.error) : new AppError(check.error);
  const rule = check.rule;
  const to = check.to as RequestStatus;

  // MDA-side actions are limited to the actor's own MDA.
  if (rule.side === "MDA" && req.mdaId !== actor.mdaId) throw new ForbiddenError();
  if (rule.side === "KATDICT" && actor.userType !== "KATDICT_STAFF") throw new ForbiddenError();
  if (action === "mda_respond" && !can(actor, "request.read.mda") && req.createdById !== actor.id) throw new ForbiddenError();

  const data: Prisma.ServiceRequestUncheckedUpdateManyInput = { status: to, version: { increment: 1 } };
  if (action === "accept_for_assessment") {
    const t = triageSchema.safeParse(payload.triage ?? {});
    if (!t.success) throw new ValidationError("Complete the triage details.", fieldErrors(t.error));
    const dept = await prisma.department.findFirst({ where: { id: t.data.assignedDepartmentId, active: true } });
    if (!dept) throw new ValidationError("Select an active department.");
    if (t.data.assessorId) {
      const assessor = await prisma.user.findFirst({ where: { id: t.data.assessorId, userType: "KATDICT_STAFF", status: "ACTIVE" } });
      if (!assessor) throw new ValidationError("Select an active KATDICT officer as assessor.");
    }
    Object.assign(data, { priority: t.data.priority, assignedDepartmentId: t.data.assignedDepartmentId, assessorId: t.data.assessorId ?? null, triagedAt: new Date() });
    payload.reason = payload.reason || t.data.note;
  }
  if (action === "submit_for_approval") {
    if (!req.proposedScope || !req.estimatedEffortDays) {
      throw new AppError("Record a scope and estimation assessment (proposed scope and effort) before submitting for approval.");
    }
  }
  if (action === "send_to_technical_evaluation") {
    const n = await prisma.requestAssessment.count({ where: { requestId: id, stage: { in: ["ASSESSMENT", "TRIAGE"] } } });
    if (!n) throw new AppError("Record an assessment before sending to technical evaluation.");
  }
  if (action === "complete_technical_evaluation") {
    const n = await prisma.requestAssessment.count({ where: { requestId: id, stage: "TECHNICAL" } });
    if (!n) throw new AppError("Record the technical evaluation findings first.");
  }
  if (to === "REJECTED") data.decidedAt = new Date();

  await prisma.$transaction(async (tx) => {
    const res = await tx.serviceRequest.updateMany({ where: { id, version: expectedVersion, status: req.status }, data });
    if (res.count !== 1) throw new ConflictError();
    await tx.requestStatusHistory.create({ data: { requestId: id, fromStatus: req.status, toStatus: to, action, actorId: actor.id, reason: payload.reason ?? null } });
    if (action === "request_information" || action === "mda_respond") {
      await tx.requestComment.create({
        data: {
          requestId: id, authorId: actor.id, body: payload.reason!, visibility: "MDA_VISIBLE",
          kind: action === "request_information" ? "CLARIFICATION_REQUEST" : "CLARIFICATION_RESPONSE",
        },
      });
    }
    await audit(tx, {
      actorId: actor.id, actorEmail: actor.email, action: `request.${action}`, entityType: "ServiceRequest", entityId: id,
      before: { status: req.status }, after: { status: to, ...(data.priority ? { priority: data.priority, assignedDepartmentId: data.assignedDepartmentId, assessorId: data.assessorId } : {}) },
      reason: payload.reason,
    });
    await notifyTransition(tx, req, to, action, actor, payload.reason);
  });
}

async function notifyTransition(
  tx: Tx,
  req: { id: string; reference: string | null; title: string; mdaId: string; createdById: string; assessorId: string | null; assignedDepartmentId: string | null },
  to: RequestStatus,
  action: string,
  actor: Actor,
  reason?: string,
) {
  const ref = req.reference ?? req.title;
  const link = `/requests/${req.id}`;
  const mdaSide = NOTIFY_MDA_ON[to];
  if (mdaSide && action !== "mda_respond") {
    const mdaAdmins = await tx.user.findMany({ where: { membership: { mdaId: req.mdaId }, roles: { some: { role: { key: "MDA_ADMIN" } } }, status: "ACTIVE" }, select: { id: true } });
    await notify(tx, {
      userIds: [req.createdById, ...mdaAdmins.map((u) => u.id)], type: mdaSide.type, title: `${mdaSide.title}: ${ref}`,
      body: reason ? `${mdaSide.title} for "${req.title}".\n\n${reason}` : `${mdaSide.title} for "${req.title}".`, link,
    });
  }
  if (action === "mda_respond") {
    const assessors = req.assessorId ? [req.assessorId] : await usersWithPermission(tx, "request.assess");
    await notify(tx, { userIds: assessors, type: "request.mda_responded", title: `MDA responded: ${ref}`, body: `${actor.name} responded to the clarification request.`, link });
  }
  if (action === "accept_for_assessment") {
    const updated = await tx.serviceRequest.findUniqueOrThrow({ where: { id: req.id }, select: { assessorId: true, assignedDepartmentId: true } });
    const ids = updated.assessorId ? [updated.assessorId] : [];
    if (updated.assignedDepartmentId) {
      const d = await tx.department.findUnique({ where: { id: updated.assignedDepartmentId }, select: { headId: true } });
      if (d?.headId) ids.push(d.headId);
    }
    await notify(tx, { userIds: ids, type: "request.assigned_for_assessment", title: `Assigned for assessment: ${ref}`, body: `"${req.title}" has been assigned for assessment.`, link });
  }
  if (to === "APPROVAL_REVIEW") {
    // Notify holders of the first pending step's permission.
    const r = await tx.serviceRequest.findUniqueOrThrow({ where: { id: req.id }, include: { service: { include: { approvalPolicy: { include: { steps: true } } } } } });
    const steps = await resolvePolicySteps(tx, r.service.approvalPolicy?.steps);
    const state = evaluateApproval(steps, toFacts(r), []);
    if (state.state === "pending") {
      const ids = await usersWithPermission(tx, state.nextStep.requiredPermission);
      await notify(tx, { userIds: ids, type: "request.approval_needed", title: `Approval needed: ${ref}`, body: `"${req.title}" awaits the ${state.nextStep.name} decision.`, link: `/approvals` });
    }
  }
}

