export async function addRequestComment(actor: Actor, requestId: string, body: string, visibility: "INTERNAL" | "MDA_VISIBLE") {
  const text = body?.trim();
  if (!text || text.length > 5000) throw new ValidationError("Message must be 1–5000 characters.");
  const req = await prisma.serviceRequest.findFirst({ where: { AND: [{ id: requestId }, requestScope(actor)] } });
  if (!req) throw new NotFoundError();
  if (req.status === "DRAFT") throw new AppError("Submit the request before adding messages.");
  const vis = actor.userType === "MDA_USER" ? "MDA_VISIBLE" : visibility;
  if (actor.userType === "MDA_USER" && req.mdaId !== actor.mdaId) throw new ForbiddenError();
  if (vis === "INTERNAL" && actor.userType !== "KATDICT_STAFF") throw new ForbiddenError();
  if (actor.userType === "OVERSIGHT") throw new ForbiddenError("Oversight accounts are read-only.");
  await prisma.$transaction(async (tx) => {
    await tx.requestComment.create({ data: { requestId, authorId: actor.id, body: text, visibility: vis } });
    if (vis === "MDA_VISIBLE") {
      if (actor.userType === "MDA_USER") {
        const ids = req.assessorId ? [req.assessorId] : await usersWithPermission(tx, "request.triage");
        await notify(tx, { userIds: ids, type: "request.mda_responded", title: `New MDA message on ${req.reference}`, body: text.slice(0, 300), link: `/requests/${req.id}`, email: false });
      } else {
        await notify(tx, { userIds: [req.createdById], type: "request.status_changed", title: `New message from KATDICT on ${req.reference}`, body: text.slice(0, 300), link: `/requests/${req.id}`, email: false });
      }
    }
  });
}

