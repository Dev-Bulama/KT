function fieldErrors(err: { flatten: () => { fieldErrors: unknown } }) {
  return err.flatten().fieldErrors as Record<string, string[]>;
}

async function assertMdaCanSubmit(actor: Actor) {
  assertCan(actor, "request.create");
  if (!actor.mdaId || actor.mdaStatus !== "ACTIVE") throw new ForbiddenError("Your MDA account must be active to submit requests.");
  if (!actor.roles.includes("MDA_ADMIN") && !actor.staffMaySubmit) {
    throw new ForbiddenError("Your MDA's policy only allows MDA administrators to submit requests.");
  }
}

