export async function resolvePolicySteps(db: Tx | typeof prisma, steps?: { id: string; sequence: number; name: string; requiredPermission: string; minPriority: string | null; minEstimatedCostNgn: unknown; minEstimatedEffortDays: number | null }[] | null): Promise<PolicyStep[]> {
  let src = steps;
  if (!src || src.length === 0) {
    const def = await db.approvalPolicy.findFirst({ where: { isDefault: true, active: true }, include: { steps: true } });
    src = def?.steps ?? [];
  }
  return src.map((s) => ({
    id: s.id, sequence: s.sequence, name: s.name, requiredPermission: s.requiredPermission,
    minPriority: (s.minPriority as PolicyStep["minPriority"]) ?? null,
    minEstimatedCostNgn: s.minEstimatedCostNgn === null || s.minEstimatedCostNgn === undefined ? null : Number(s.minEstimatedCostNgn),
    minEstimatedEffortDays: s.minEstimatedEffortDays,
  }));
}

function toFacts(r: { priority: string | null; estimatedCostNgn: unknown; estimatedEffortDays: number | null }) {
  return {
    priority: (r.priority as PolicyStep["minPriority"]) ?? null,
    estimatedCostNgn: r.estimatedCostNgn === null || r.estimatedCostNgn === undefined ? null : Number(r.estimatedCostNgn),
    estimatedEffortDays: r.estimatedEffortDays,
  };
}

async function currentCycle(db: Tx | typeof prisma, requestId: string): Promise<number> {
  const entries = await db.requestStatusHistory.count({ where: { requestId, toStatus: "APPROVAL_REVIEW" } });
  return Math.max(1, entries);
}

export async function getApprovalState(requestId: string) {
  const r = await prisma.serviceRequest.findUniqueOrThrow({ where: { id: requestId }, include: { service: { include: { approvalPolicy: { include: { steps: true } } } } } });
  const steps = await resolvePolicySteps(prisma, r.service.approvalPolicy?.steps);
  const cycle = await currentCycle(prisma, requestId);
  const decisions = await prisma.approvalDecision.findMany({ where: { requestId, cycle } });
  return { steps, cycle, state: evaluateApproval(steps, toFacts(r), decisions), decisions };
}

/** Lists requests whose next pending approval step the actor may decide. */
export async function listApprovalQueue(actor: Actor) {
  const candidates = await prisma.serviceRequest.findMany({
    where: { AND: [{ status: "APPROVAL_REVIEW" }, requestScope(actor)] },
    include: { mda: { select: { name: true, abbreviation: true } }, service: { include: { approvalPolicy: { include: { steps: true } } } } },
    orderBy: { updatedAt: "asc" },
    take: 200,
  });
  const out = [];
  for (const r of candidates) {
    const steps = await resolvePolicySteps(prisma, r.service.approvalPolicy?.steps);
    const cycle = await currentCycle(prisma, r.id);
    const decisions = await prisma.approvalDecision.findMany({ where: { requestId: r.id, cycle } });
    const state = evaluateApproval(steps, toFacts(r), decisions);
    const mine = state.state === "pending" && actor.permissions.has(state.nextStep.requiredPermission) && !decisions.some((d) => d.decidedById === actor.id);
    out.push({ request: r, state, canDecide: mine });
  }
  return out;
}

export async function decideApproval(actor: Actor, requestId: string, outcome: "APPROVED" | "REJECTED" | "RETURNED", reason: string | undefined, expectedVersion: number) {
  if ((outcome === "REJECTED" || outcome === "RETURNED") && !reason?.trim()) throw new ValidationError("A reason is required.");
  const r = await prisma.serviceRequest.findFirst({
    where: { AND: [{ id: requestId }, requestScope(actor)] },
    include: { service: { include: { approvalPolicy: { include: { steps: true } } } } },
  });
  if (!r) throw new NotFoundError();
  const check = checkRequestTransition("approval_decision", r.status, actor.permissions);
  if (!check.ok) throw check.code === "FORBIDDEN" ? new ForbiddenError(check.error) : new AppError(check.error);
  if (actor.userType !== "KATDICT_STAFF") throw new ForbiddenError();

  await prisma.$transaction(async (tx) => {
    const steps = await resolvePolicySteps(tx, r.service.approvalPolicy?.steps);
    const cycle = await currentCycle(tx, requestId);
    const decisions = await tx.approvalDecision.findMany({ where: { requestId, cycle } });
    const state = evaluateApproval(steps, toFacts(r), decisions);
    let newStatus: RequestStatus | null = null;

    if (state.state === "no_steps") {
      throw new AppError("No approval policy is configured for this service. Configure one in Admin › Service catalog.");
    }
    if (state.state !== "pending") throw new AppError("This request has no pending approval step.");
    const step = state.nextStep;
    if (!actor.permissions.has(step.requiredPermission)) throw new ForbiddenError(`The "${step.name}" step requires a different approval authority.`);
    // Separation of duties: one person cannot approve two steps of the same cycle,
    // and the officer who scoped the request cannot approve it.
    if (decisions.some((d) => d.decidedById === actor.id)) throw new ForbiddenError("You have already recorded a decision on this request in this approval cycle.");
    const scopedBySelf = await tx.requestAssessment.findFirst({ where: { requestId, stage: "SCOPE", assessorId: actor.id } });
    if (scopedBySelf && outcome === "APPROVED") throw new ForbiddenError("The officer who prepared the scope cannot approve it.");

    await tx.approvalDecision.create({ data: { requestId, stepId: step.id, cycle, decidedById: actor.id, outcome, reason: reason ?? null } });
    const after = evaluateApproval(steps, toFacts(r), [...decisions, { stepId: step.id, outcome }]);
    if (after.state === "approved") newStatus = "APPROVED";
    else if (after.state === "rejected") newStatus = "REJECTED";
    else if (after.state === "returned") newStatus = "RETURNED_FOR_REVISION";

    if (newStatus) {
      const res = await tx.serviceRequest.updateMany({
        where: { id: requestId, version: expectedVersion, status: "APPROVAL_REVIEW" },
        data: { status: newStatus, version: { increment: 1 }, decidedAt: new Date(), ...(newStatus === "APPROVED" ? { approvedAt: new Date() } : {}) },
      });
      if (res.count !== 1) throw new ConflictError();
      await tx.requestStatusHistory.create({ data: { requestId, fromStatus: "APPROVAL_REVIEW", toStatus: newStatus, action: `approval_${outcome.toLowerCase()}`, actorId: actor.id, reason: reason ?? null } });
    } else {
      const res = await tx.serviceRequest.updateMany({ where: { id: requestId, version: expectedVersion }, data: { version: { increment: 1 } } });
      if (res.count !== 1) throw new ConflictError();
    }
    await audit(tx, {
      actorId: actor.id, actorEmail: actor.email, action: `request.approval.${outcome.toLowerCase()}`, entityType: "ServiceRequest", entityId: requestId,
      before: { status: "APPROVAL_REVIEW" }, after: { step: step.name, cycle, outcome, status: newStatus ?? "APPROVAL_REVIEW" }, reason,
    });

    const ref = r.reference ?? r.title;
    const mdaUsers = await tx.user.findMany({ where: { membership: { mdaId: r.mdaId }, roles: { some: { role: { key: "MDA_ADMIN" } } }, status: "ACTIVE" }, select: { id: true } });
    const mdaIds = [r.createdById, ...mdaUsers.map((u) => u.id)];
    if (newStatus === "APPROVED") {
      await notify(tx, { userIds: mdaIds, type: "request.approved", title: `Request approved: ${ref}`, body: `"${r.title}" has been approved. KATDICT will initiate the project and assign a delivery team.`, link: `/requests/${r.id}` });
      await notify(tx, { userIds: await usersWithPermission(tx, "project.create"), type: "request.approved", title: `Ready for project initiation: ${ref}`, body: `"${r.title}" is approved and awaits project initiation.`, link: `/requests/${r.id}` });
    } else if (newStatus === "REJECTED") {
      await notify(tx, { userIds: mdaIds, type: "request.rejected", title: `Request not approved: ${ref}`, body: `"${r.title}" was not approved.\n\nReason: ${reason}`, link: `/requests/${r.id}` });
    } else if (newStatus === "RETURNED_FOR_REVISION") {
      await notify(tx, { userIds: await usersWithPermission(tx, "request.scope"), type: "request.status_changed", title: `Returned for revision: ${ref}`, body: `The ${step.name} step returned the request.\n\nReason: ${reason}`, link: `/requests/${r.id}` });
    } else if (after.state === "pending") {
      await notify(tx, { userIds: await usersWithPermission(tx, after.nextStep.requiredPermission), type: "request.approval_needed", title: `Approval needed: ${ref}`, body: `"${r.title}" awaits the ${after.nextStep.name} decision.`, link: `/approvals` });
    }
  });
}

