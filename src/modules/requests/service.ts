export interface RequestListFilters {
  q?: string;
  status?: string;
  mdaId?: string;
  categoryId?: string;
  departmentId?: string;
  priority?: string;
  from?: Date;
  to?: Date;
  page?: number;
  pageSize?: number;
  sort?: "newest" | "oldest" | "priority";
}

export async function listRequests(actor: Actor, f: RequestListFilters = {}) {
  const page = Math.max(1, f.page ?? 1);
  const pageSize = Math.min(100, Math.max(5, f.pageSize ?? 20));
  const where: Prisma.ServiceRequestWhereInput = {
    AND: [
      requestScope(actor),
      f.q ? { OR: [{ title: { contains: f.q, mode: "insensitive" } }, { reference: { contains: f.q, mode: "insensitive" } }] } : {},
      f.status ? { status: f.status as RequestStatus } : {},
      f.mdaId ? { mdaId: f.mdaId } : {},
      f.categoryId ? { service: { categoryId: f.categoryId } } : {},
      f.departmentId ? { assignedDepartmentId: f.departmentId } : {},
      f.priority ? { priority: f.priority as never } : {},
      f.from || f.to ? { submittedAt: { ...(f.from ? { gte: f.from } : {}), ...(f.to ? { lte: f.to } : {}) } } : {},
    ],
  };
  const orderBy: Prisma.ServiceRequestOrderByWithRelationInput[] =
    f.sort === "oldest" ? [{ createdAt: "asc" }] : f.sort === "priority" ? [{ priority: "desc" }, { submittedAt: "asc" }] : [{ updatedAt: "desc" }];
  const [items, total] = await Promise.all([
    prisma.serviceRequest.findMany({
      where, orderBy, skip: (page - 1) * pageSize, take: pageSize,
      select: {
        id: true, reference: true, title: true, status: true, priority: true, urgency: true, submittedAt: true, updatedAt: true,
        mda: { select: { id: true, name: true, abbreviation: true } },
        service: { select: { name: true, category: { select: { name: true } } } },
        assignedDepartment: { select: { name: true } },
      },
    }),
    prisma.serviceRequest.count({ where }),
  ]);
  return { items, total, page, pageSize };
}

export async function getRequest(actor: Actor, id: string) {
  const internal = canSeeInternal(actor) || (actor.userType !== "MDA_USER");
  const req = await prisma.serviceRequest.findFirst({
    where: { AND: [{ id }, requestScope(actor)] },
    include: {
      mda: { select: { id: true, name: true, abbreviation: true } },
      service: { include: { category: true, approvalPolicy: { include: { steps: { orderBy: { sequence: "asc" } } } } } },
      createdBy: { select: { id: true, name: true, email: true } },
      assignedDepartment: { select: { id: true, name: true } },
      assessor: { select: { id: true, name: true } },
      history: { orderBy: { createdAt: "asc" }, include: { actor: { select: { name: true, userType: true } } } },
      comments: {
        where: internal ? {} : { visibility: "MDA_VISIBLE" },
        orderBy: { createdAt: "asc" },
        include: { author: { select: { name: true, userType: true } } },
      },
      attachments: { where: internal ? {} : { visibility: "MDA_VISIBLE" }, orderBy: { createdAt: "asc" } },
      // Loaded for typing; stripped below for MDA users.
      assessments: { orderBy: { createdAt: "asc" }, include: { assessor: { select: { name: true } } } },
      approvalDecisions: { orderBy: { createdAt: "asc" }, include: { step: true, decidedBy: { select: { name: true } } } },
      project: { select: { id: true, reference: true, status: true } },
    },
  });
  if (!req) throw new NotFoundError();
  if (actor.userType === "MDA_USER") {
    // MDA users see decisions but not internal estimates or assessor identity.
    return { ...req, estimatedCostNgn: null, assessments: [], assessor: null, history: req.history.map((h) => ({ ...h, actor: h.actor ? { name: h.actor.userType === "MDA_USER" ? h.actor.name : "KATDICT", userType: h.actor.userType } : null })) };
  }
  return req;
}

