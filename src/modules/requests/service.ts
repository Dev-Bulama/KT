const STAGE_PERMISSION = {
  TRIAGE: "request.triage",
  ASSESSMENT: "request.assess",
  TECHNICAL: "request.evaluate.technical",
  SCOPE: "request.scope",
} as const;

const STAGE_STATUSES: Record<keyof typeof STAGE_PERMISSION, RequestStatus[]> = {
  TRIAGE: ["SUBMITTED", "INITIAL_TRIAGE"],
  ASSESSMENT: ["UNDER_ASSESSMENT"],
  TECHNICAL: ["TECHNICAL_EVALUATION"],
  SCOPE: ["SCOPE_ESTIMATION", "RETURNED_FOR_REVISION"],
};

export async function recordAssessment(actor: Actor, requestId: string, raw: unknown) {
  const parsed = assessmentSchema.safeParse(raw);
  if (!parsed.success) throw new ValidationError("Please correct the highlighted fields.", fieldErrors(parsed.error));
  const a = parsed.data;
  assertCan(actor, STAGE_PERMISSION[a.stage]);
  const req = await prisma.serviceRequest.findFirst({ where: { AND: [{ id: requestId }, requestScope(actor)] } });
  if (!req) throw new NotFoundError();
  if (!STAGE_STATUSES[a.stage].includes(req.status)) throw new AppError(`A ${a.stage.toLowerCase()} assessment cannot be recorded while the request is ${req.status.replace(/_/g, " ").toLowerCase()}.`);
  if (a.stage === "SCOPE" && (!a.proposedScope || !a.estimatedEffortDays)) throw new ValidationError("Scope assessments require a proposed scope and estimated effort.");
  await prisma.$transaction(async (tx) => {
    const rec = await tx.requestAssessment.create({
      data: {
        requestId, stage: a.stage, assessorId: actor.id, findings: a.findings, recommendation: a.recommendation ?? null,
        recommendedPriority: a.recommendedPriority ?? null, estimatedEffortDays: a.estimatedEffortDays ?? null,
        estimatedCostNgn: a.estimatedCostNgn ?? null, proposedScope: a.proposedScope ?? null, checklist: a.checklist ?? undefined,
      },
    });
    if (a.stage === "SCOPE") {
      await tx.serviceRequest.update({
        where: { id: requestId },
        data: { proposedScope: a.proposedScope, estimatedEffortDays: a.estimatedEffortDays, estimatedCostNgn: a.estimatedCostNgn ?? null, ...(a.recommendedPriority ? { priority: a.recommendedPriority } : {}), version: { increment: 1 } },
      });
    } else if (a.recommendedPriority && can(actor, "request.triage")) {
      await tx.serviceRequest.update({ where: { id: requestId }, data: { priority: a.recommendedPriority, version: { increment: 1 } } });
    }
    await audit(tx, { actorId: actor.id, actorEmail: actor.email, action: "request.assessment_recorded", entityType: "ServiceRequest", entityId: requestId, after: { assessmentId: rec.id, stage: a.stage, estimatedEffortDays: a.estimatedEffortDays, estimatedCostNgn: a.estimatedCostNgn } });
  });
}

